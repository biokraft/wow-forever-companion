import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { addonsDir, isGameDir } from './detect.js';

export const PLAN_FILE = 'ForeverLog_Plan.lua';
const EMPTY_PLAN = '-- Generated by wowf plan write. No plan yet.\nForeverLogPlan = nil\n';

export function addonSourceDir() {
  return fileURLToPath(new URL('../addon/ForeverLog', import.meta.url));
}

/** Copies (or links) addon/ForeverLog into the game's AddOns folder. Returns the installed path. */
export function installAddon(gameDir, { link = false } = {}) {
  if (!isGameDir(gameDir)) throw new Error(`${gameDir} is not a WoW: Forever folder (expected the _forever_ folder)`);
  const target = addonsDir(gameDir);
  fs.mkdirSync(target, { recursive: true }); // fresh installs have no AddOns folder yet
  const dest = path.join(target, 'ForeverLog');
  const planFile = path.join(dest, PLAN_FILE);
  const keptPlan = fs.existsSync(planFile) ? fs.readFileSync(planFile) : null;
  // lstat so an existing symlink is removed itself, never the folder it points at
  if (fs.lstatSync(dest, { throwIfNoEntry: false })) fs.rmSync(dest, { recursive: true, force: true });
  if (link) {
    fs.symlinkSync(addonSourceDir(), dest, process.platform === 'win32' ? 'junction' : 'dir');
  } else {
    fs.cpSync(addonSourceDir(), dest, { recursive: true, filter: (src) => path.basename(src) !== PLAN_FILE });
  }
  // The .toc loads the plan file, so it must exist; keep the player's current plan.
  if (keptPlan) fs.writeFileSync(planFile, keptPlan);
  else if (!fs.existsSync(planFile)) fs.writeFileSync(planFile, EMPTY_PLAN);
  return dest;
}
