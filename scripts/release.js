#!/usr/bin/env node
// Builds a release without publishing anything:
//   node scripts/release.js        -> dist/public/ (clean tree, tested + scanned) and dist/ForeverLog-<v>.zip
// Publishing (the tag and the GitHub release) is done by the release skill and workflow.
// dist/public/ holds its own throwaway .git with a placeholder author: when a public repo is
// created from that tree, copy the files WITHOUT that .git and commit under the real author.
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { scanFiles } from './privacy-scan.js';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const EMPTY_PLAN = '-- Generated by wowf plan write. No plan yet.\nForeverLogPlan = nil\n';

const PRIVATE_PREFIXES = ['docs/superpowers/', 'scratch/', '.superpowers/'];

export function workingTreeDirty() {
  return execFileSync('git', ['-C', ROOT, 'status', '--porcelain'], { encoding: 'utf8' }).trim() !== '';
}

// Exports the last commit (never the working folder), drops private paths, normalizes modes.
export function buildPublicTree(outDir, ref = 'HEAD') {
  fs.rmSync(outDir, { recursive: true, force: true });
  fs.mkdirSync(outDir, { recursive: true });
  const tar = path.join(os.tmpdir(), `forevercompanion-${process.pid}-${Date.now()}.tar`);
  execFileSync('git', ['-C', ROOT, 'archive', '--format=tar', '-o', tar, ref]);
  execFileSync('tar', ['-xf', tar, '-C', outDir]);
  fs.rmSync(tar, { force: true });
  for (const p of PRIVATE_PREFIXES) fs.rmSync(path.join(outDir, p), { recursive: true, force: true });
  const files = [];
  const walk = (dir) => {
    for (const d of fs.readdirSync(dir, { withFileTypes: true })) {
      const full = path.join(dir, d.name);
      if (d.isDirectory()) { fs.chmodSync(full, 0o755); walk(full); continue; }
      const rel = path.relative(outDir, full).split(path.sep).join('/');
      if (rel.endsWith('ForeverLog_Plan.lua')) { fs.rmSync(full); continue; }
      fs.chmodSync(full, rel.startsWith('bin/') || rel.endsWith('.sh') ? 0o755 : 0o644);
      files.push(rel);
    }
  };
  walk(outDir);
  return files.sort();
}

// Zips the addon from the exported tree, adding the empty plan file the .toc loads.
export function buildAddonZip(treeDir, outDir, version) {
  const staging = fs.mkdtempSync(path.join(os.tmpdir(), 'forevercompanion-zip-'));
  try {
    const addon = path.join(staging, 'ForeverLog');
    fs.cpSync(path.join(treeDir, 'addon', 'ForeverLog'), addon, { recursive: true });
    fs.writeFileSync(path.join(addon, 'ForeverLog_Plan.lua'), EMPTY_PLAN, { mode: 0o644 });
    const hits = scanFiles(fs.readdirSync(addon).map((f) => path.join(addon, f)));
    if (hits.length) throw new Error(`personal data in the addon zip: ${hits.map((h) => `${path.basename(h.file)}:${h.line}`).join(', ')}`);
    fs.mkdirSync(outDir, { recursive: true });
    const zip = path.join(outDir, `ForeverLog-${version}.zip`);
    fs.rmSync(zip, { force: true });
    execFileSync('zip', ['-qrX', zip, 'ForeverLog'], { cwd: staging });
    return zip;
  } finally {
    fs.rmSync(staging, { recursive: true, force: true });
  }
}

function run(cmd, args, cwd) {
  process.stdout.write(`$ ${cmd} ${args.join(' ')}\n`);
  execFileSync(cmd, args, { cwd, stdio: 'inherit' });
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  if (workingTreeDirty() && !process.argv.includes('--allow-dirty')) {
    process.stderr.write('Refusing to release: commit or stash your changes first (the release is built from HEAD).\n');
    process.exit(1);
  }
  const version = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8')).version;
  const dist = path.join(ROOT, 'dist');
  const tree = path.join(dist, 'public');
  const files = buildPublicTree(tree);
  process.stdout.write(`public tree: ${files.length} files in ${tree}\n`);
  const hits = scanFiles(files.map((f) => path.join(tree, f)));
  if (hits.length) {
    for (const h of hits) process.stderr.write(`${path.relative(tree, h.file)}:${h.line}: personal data "${h.match}"\n`);
    process.exit(1);
  }
  run('git', ['init', '-q'], tree);
  run('git', ['add', '-A'], tree); // tests list files through git
  // The release tests export HEAD, so the tree needs a commit. Placeholder identity:
  // before publishing, amend it with the publisher's own (noreply) author.
  run('git', ['-c', 'user.name=Forever Companion release', '-c', 'user.email=release@localhost',
    '-c', 'commit.gpgsign=false', 'commit', '-q', '-m', `Forever Companion ${version}`], tree);
  run(process.platform === 'win32' ? 'npm.cmd' : 'npm', ['test', '--silent'], tree);
  // One overlay test file per process (the combined run hangs on the owner's machine).
  run('node', ['scripts/test-overlay.js'], tree);
  run('luajit', ['addon/test/run.lua'], tree);
  process.stdout.write(`addon zip: ${buildAddonZip(tree, dist, version)}\n`);
  process.stdout.write('Release built. Nothing was published.\n');
}
