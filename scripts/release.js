#!/usr/bin/env node
// Builds the addon zip a release carries, without publishing anything:
//   node scripts/release.js        -> dist/ForeverLog-<version>.zip
// Publishing (the tag and the GitHub release) is done by the release skill and workflow.
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { scanFiles } from './privacy-scan.js';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const ADDON = 'addon/ForeverLog';
const PLAN_FILE = 'ForeverLog_Plan.lua';
const EMPTY_PLAN = '-- Generated by wowf plan write. No plan yet.\nForeverLogPlan = nil\n';

export function workingTreeDirty() {
  return execFileSync('git', ['-C', ROOT, 'status', '--porcelain'], { encoding: 'utf8' }).trim() !== '';
}

// Zips the addon as the commit has it (never the working folder, so no local plan and no
// stray file gets in), adding the empty plan file the .toc loads.
export function buildAddonZip(outDir, version, ref = 'HEAD') {
  // zip runs inside a temporary folder, so the output folder must not depend on the current one.
  outDir = path.resolve(outDir);
  const staging = fs.mkdtempSync(path.join(os.tmpdir(), 'forevercompanion-zip-'));
  try {
    const tar = path.join(staging, 'addon.tar');
    execFileSync('git', ['-C', ROOT, 'archive', '--format=tar', '-o', tar, ref, ADDON]);
    execFileSync('tar', ['-xf', tar, '-C', staging]);
    const addon = path.join(staging, 'ForeverLog');
    fs.renameSync(path.join(staging, ...ADDON.split('/')), addon);
    fs.writeFileSync(path.join(addon, PLAN_FILE), EMPTY_PLAN);
    for (const f of fs.readdirSync(addon)) fs.chmodSync(path.join(addon, f), 0o644);
    const hits = scanFiles(fs.readdirSync(addon).map((f) => path.join(addon, f)));
    if (hits.length) throw new Error(`personal data in the addon zip: ${hits.map((h) => `${path.basename(h.file)}:${h.line}`).join(', ')}`);
    fs.mkdirSync(outDir, { recursive: true });
    const zip = path.join(outDir, `ForeverLog-${version}.zip`);
    fs.rmSync(zip, { force: true });
    execFileSync('zip', ['-qrX', zip, 'ForeverLog'], { cwd: staging });
    return zip;
  } finally {
    fs.rmSync(staging, { recursive: true, force: true });
  }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  if (workingTreeDirty()) {
    process.stderr.write('Refusing to build: commit or stash your changes first (the zip is built from the last commit).\n');
    process.exit(1);
  }
  const version = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8')).version;
  process.stdout.write(`addon zip: ${buildAddonZip(path.join(ROOT, 'dist'), version)}\n`);
  process.stdout.write('Nothing was published.\n');
}
